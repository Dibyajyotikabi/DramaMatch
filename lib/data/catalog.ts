import type { Drama, DramaDNA, Person } from "../types";
export const slugify = (text: string) =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
const cast = (actress: string, actor: string): Person[] => [
  { name: actress, slug: slugify(actress), kind: "actress" },
  { name: actor, slug: slugify(actor), kind: "actor" },
];
